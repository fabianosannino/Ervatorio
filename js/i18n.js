// ─── State ───────────────────────────────────────────────
let _lang = 'pt';

// ─── Public API ─────────────────────────────────────────
function t(key) {
  return TRANSLATIONS[_lang]?.[key] ?? TRANSLATIONS.pt[key] ?? key;
}

function setLang(lang) {
  if (!TRANSLATIONS[lang]) return;
  _lang = lang;
  window._lang = lang;
  localStorage.setItem('erb_lang', lang);
  applyI18n();
  renderLangSwitcher();
  if (typeof updateSEO === 'function') updateSEO(window._currentPage || 'search');
}

function getLang() { return _lang; }

// ─── DOM application ────────────────────────────────────
function applyI18n() {
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    const val = t(key);
    if (val !== key) el.textContent = val;
  });
  // data-i18n-html: usado quando o conteúdo traduzido contém marcação
  // segura controlada (ex.: <br>, <em>) — landing hero headline.
  document.querySelectorAll('[data-i18n-html]').forEach(el => {
    const key = el.getAttribute('data-i18n-html');
    const val = t(key);
    if (val !== key) el.innerHTML = val;
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    const val = t(key);
    if (val && val !== key) el.placeholder = val;
  });
  document.querySelectorAll('[data-i18n-title]').forEach(el => {
    const key = el.getAttribute('data-i18n-title');
    const val = t(key);
    if (val && val !== key) el.title = val;
  });
  // Rótulo acessível de ícones (handoff 14/09): todo ícone tem texto ou aria-label.
  document.querySelectorAll('[data-i18n-aria]').forEach(el => {
    const key = el.getAttribute('data-i18n-aria');
    const val = t(key);
    if (val && val !== key) el.setAttribute('aria-label', val);
  });
  // O menu em grupos é gerado por JS com as chaves nav.* — refaz ao trocar idioma.
  if (typeof renderNav === 'function') renderNav();
  document.documentElement.lang = LANGS[_lang]?.locale || 'pt-BR';
}

// ─── Language switcher UI ────────────────────────────────
function renderLangSwitcher() {
  // Lista os visíveis e, se o idioma atual não for um deles, ele também —
  // senão o seletor mostraria dois botões, nenhum ativo.
  const html = Object.entries(LANGS)
    .filter(([code, info]) => info.visible || code === _lang)
    .map(([code, info]) =>
    `<button class="lang-btn${_lang === code ? ' on' : ''}"
             onclick="setLang('${code}')"
             lang="${info.locale}"
             title="${info.name}"
             aria-label="${info.name}"
             aria-pressed="${_lang === code ? 'true' : 'false'}">
       ${info.code}
     </button>`
  ).join('');
  // Renderiza em todos os containers (.lang-switcher) — header do app E
  // header da landing page têm o mesmo seletor.
  document.querySelectorAll('.lang-switcher').forEach(el => { el.innerHTML = html; });
}

// ─── Init ────────────────────────────────────────────────
function initI18n() {
  const stored  = localStorage.getItem('erb_lang');
  const browser = (navigator.language || 'pt').split('-')[0];
  const supported = Object.keys(TRANSLATIONS);
  // Map common browser codes
  const browserMap = { 'pt': 'pt', 'en': 'en', 'es': 'es', 'ja': 'ja', 'de': 'de', 'fr': 'fr' };
  _lang = supported.includes(stored)            ? stored
        : supported.includes(browserMap[browser]) ? browserMap[browser]
        : 'pt';
  window._lang = _lang;
  renderLangSwitcher();
  applyI18n();
}
